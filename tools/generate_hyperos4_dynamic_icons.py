"""Generate pinned 6144 async icon-source snapshots from the user's launcher APK.

The branch after InitAsync targets the existing null-completion block, preserving
the Dart Future ABI. No Dart function is replaced with a C ABI callback.
"""
import pathlib
import hashlib
import struct
import sys
import zipfile

FUNCTIONS = (
    ("Fancy", 0x191A164, 1084, 0x191A184, 0xF85F03A1, 0x191A594, 0xAA1603E0),
    ("Animating", 0x191A624, 1084, 0x191A644, 0xF85F03A1, 0x191AA54, 0xAA1603E0),
    ("MamlAdaptive", 0x191AEFC, 1084, 0x191AF1C, 0xF85F03A1, 0x191B32C, 0xAA1603E0),
    ("ThemeSource", 0x1AAD3E0, 392, 0x1AAD408, 0xF85E83A5, 0x1AAD430, 0x9140C760),
    ("AiHdSource", 0x1AAACA0, 568, 0x1AAACC4, 0xF85703A0, 0x1AAACD4, 0x9140C760),
    ("ModSource", 0x1AAB660, 516, 0x1AAB688, 0xF9403F40, 0x1AAB6C0, 0xF85E83A5),
    ("ModStyle", 0x17E743C, 64, 0x17E743C, 0xA9BF79FD, 0x1AAB284, 0xA9BF79FD),
    ("ThemeStyle", 0x1AAB284, 248, 0x1AAB2B8, 0x94000031, 0x1AAB314, 0xF85E83A0),
)

def generate(apk):
    with zipfile.ZipFile(apk) as archive:
        data = archive.read("lib/arm64-v8a/libapp.so")
    assert hashlib.sha256(data).hexdigest() == "60c8c7a47634b3474dd9e1052f996473882456e87b0f37a2bfe1fe377c413ce9"
    lines = ["// Generated by tools/generate_hyperos4_dynamic_icons.py from MiuiHome_6144.apk.",
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace monoicon::hyperos4::dynamic6144 {"]
    assert struct.unpack_from("<I", data, 0x1AAB6D4)[0] == 0x94000280
    for name, start, size, patch, original, completion, result in FUNCTIONS:
        assert struct.unpack_from("<I", data, patch)[0] == original
        assert struct.unpack_from("<I", data, completion)[0] == result
        branch = 0x14000000 | (((completion - patch) // 4) & 0x3FFFFFF)
        lines += [f"constexpr uint32_t k{name}Vaddr = 0x{start:x};",
                  f"constexpr uint32_t k{name}Patch = 0x{patch:x};",
                  f"constexpr uint32_t k{name}Branch = 0x{branch:08x};",
                  f"constexpr std::array<uint8_t, {size}> k{name}Original{{{{"]
        for offset in range(start, start + size, 16):
            chunk = data[offset:min(offset + 16, start + size)]
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
        lines.append("}};")
    lines.append("}")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    pathlib.Path(sys.argv[2]).write_text(generate(sys.argv[1]), encoding="utf-8")
